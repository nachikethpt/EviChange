r"""Paper tables and figure from the adjudicated claims (Phase 5 -> Phase 8).

    python -m eval.adjudication reports_sites.jsonl data\adjudication\sites_p3.jsonl claims.jsonl runs.jsonl
    python scripts\results_tables.py claims.jsonl runs.jsonl --out docs\results

writes into --out:
  results.md       every table below, in Markdown
  table_main.tex   Table 1 as a LaTeX tabular (booktabs)
  figure_rates.svg hallucination and post-gate hallucination rate per condition with 95 % CIs, and the
                   pre-specified primary effect (gated minus ungated, post-gate) with its paired CI
  report.json      the full eval.metrics.report() output the tables come from

Tables: 1 per-condition rates (pooled), 2 by stratum, 3 verifier, 4 informativeness and parse failures,
5 by claim type, 6 the pre-specified comparisons, 7 detector. Everything comes from eval/metrics.py;
this script only formats.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from agents.schema import REPORT_CONDITIONS          # noqa: E402
from eval import metrics                             # noqa: E402

NAMES = {"template": "Template", "ungated": "Ungated (Qwen)", "gated": "Gated (Qwen)", "ungated_gpt": "Ungated (GPT)"}


def pct(ci) -> str:
    """'12.3 % [4.1, 20.0]' for a (rate, lo, hi) tuple; 'n/a' when undefined."""
    if not ci or ci[0] is None:
        return "n/a"
    return f"{100 * ci[0]:.1f} % [{100 * ci[1]:.1f}, {100 * ci[2]:.1f}]"


def num(v, digits: int = 2) -> str:
    return "n/a" if v is None else f"{v:.{digits}f}"


def p(v) -> str:
    return "n/a" if v is None else ("< 0.001" if v < 0.001 else f"{v:.3f}")


def md_table(head: list[str], rows: list[list[str]]) -> str:
    out = ["| " + " | ".join(head) + " |", "|" + "|".join("---" for _ in head) + "|"]
    out += ["| " + " | ".join(r) + " |" for r in rows]
    return "\n".join(out)


def conditions(rep: dict) -> list[str]:
    return [c for c in REPORT_CONDITIONS if c in rep["conditions"]]


def table_main(rep: dict) -> tuple[list[str], list[list[str]]]:
    head = ["Condition", "Claims", "Passed", "Hallucination", "Post-gate hallucination", "Unsupported", "Faithful but false"]
    rows = []
    for c in conditions(rep):
        r = rep["conditions"][c]["pooled"]
        rows.append([NAMES[c], str(r["n_claims"]), str(r["n_passed"]), pct(r["hallucination"]),
                     pct(r["post_gate_hallucination"]), pct(r["unsupported"]), pct(r["faithful_but_false"])])
    return head, rows


def tables(rep: dict) -> str:
    parts = ["# Results tables", "",
             "Generated by `scripts/results_tables.py` from `eval/metrics.py`. Claim-level rates: pooled, with a "
             "site-level cluster bootstrap 95 % CI. Site-level proportions: Wilson 95 % CI.", ""]
    head, rows = table_main(rep)
    parts += ["## Table 1. Claim rates per condition (all sites)", "", md_table(head, rows), ""]

    rows = []
    for c in conditions(rep):
        for stratum in ("detected", "random"):
            r = rep["conditions"][c][stratum]
            rows.append([NAMES[c], stratum, str(r["n_claims"]), pct(r["hallucination"]), pct(r["post_gate_hallucination"])])
    parts += ["## Table 2. By stratum", "", md_table(["Condition", "Stratum", "Claims", "Hallucination", "Post-gate"], rows), ""]

    rows = []
    for c in conditions(rep):
        v = rep["conditions"][c]["verifier"]
        rows.append([NAMES[c], pct(v["catch_rate"]), pct(v["precision"]), num(v["kappa_vs_support"])])
    parts += ["## Table 3. Verifier against the human labels", "",
              md_table(["Condition", "Catch rate", "Precision of rejections", "κ vs human support"], rows), ""]

    rows = []
    for c in conditions(rep):
        i = rep["conditions"][c]["informativeness"]
        rows.append([NAMES[c], num(i["true_claims_per_site"]), num(i["change_type_recall"]), pct(i["abstention"]),
                     pct(rep["conditions"][c]["parse_failures"])])
    parts += ["## Table 4. Informativeness and parse failures", "",
              md_table(["Condition", "True claims / site", "Change-type recall", "Abstention (no claim)", "Parse failures"], rows), ""]

    rows = []
    for c in conditions(rep):
        for t, r in rep["conditions"][c]["by_claim_type"].items():
            rows.append([NAMES[c], t, str(r["n"]), pct(r["hallucination"]), pct(r["post_gate_hallucination"])])
    parts += ["## Table 5. By claim type", "", md_table(["Condition", "Type", "Claims", "Hallucination", "Post-gate"], rows), ""]

    rows = []
    for name, cmp in rep["comparisons"].items():
        label = "primary" if name == "primary" else "secondary (D16)"
        rows.append([f"{NAMES[cmp['a']]} − {NAMES[cmp['b']]}", label, pct(cmp["pooled_rate_diff"]),
                     f"{cmp['a_fewer_on']} / {cmp['b_fewer_on']} / {cmp['sites'] - cmp['a_fewer_on'] - cmp['b_fewer_on']}",
                     p((cmp["rate_wilcoxon"] or (None, None))[1]), p(cmp["rate_sign"][2]),
                     f"{cmp['sites_with_rates']} ({cmp['sites_without_rates']} without a rate)"])
    parts += ["## Table 6. Pre-specified comparisons (post-gate hallucination)", "",
              md_table(["Comparison", "", "Pooled rate difference [95 % CI]", "Sites a better / b better / tied (counts)",
                        "Wilcoxon p (rates)", "Sign p (rates)", "Sites with rates"], rows), ""]

    d = rep["detector"]
    parts += ["## Table 7. Detector", "", md_table(["Measure", "Value", "Unsure (left out)"], [
        ["Precision (detected sites labelled change)", pct(d["precision"]), str(d["detected_unsure"])],
        ["Background change rate (random sites labelled change)", pct(d["background_change_rate"]), str(d["random_unsure"])]]), ""]
    return "\n".join(parts)


def latex_main(rep: dict) -> str:
    head, rows = table_main(rep)
    esc = lambda s: s.replace("%", r"\%").replace("−", "--")
    lines = [r"\begin{tabular}{l" + "r" * (len(head) - 1) + "}", r"\toprule",
             " & ".join(esc(h) for h in head) + r" \\", r"\midrule"]
    lines += [" & ".join(esc(c) for c in r) + r" \\" for r in rows]
    lines += [r"\bottomrule", r"\end{tabular}", ""]
    return "\n".join(lines)


# ---------- figure ----------
SERIES = (("hallucination", "All claims", "#2a78d6"), ("post_gate_hallucination", "Passed by the verifier", "#eb6834"))
INK, MUTED, GRID, SURFACE = "#0b0b0b", "#52514e", "#e4e3df", "#fcfcfb"


def figure(rep: dict) -> str:
    """Dot-and-interval chart, one row per condition, 0-100 % on one shared axis; below it the primary
    effect (gated minus ungated, post-gate) on its own axis. Static SVG for the paper; every mark has a
    <title> tooltip for on-screen reading."""
    conds = conditions(rep)
    left, right, row_h, top = 150, 30, 46, 54
    width = 720
    plot_w = width - left - right
    rates_h = top + row_h * len(conds) + 34
    x = lambda v: left + plot_w * v
    out = [f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {width} {rates_h + 150}" width="{width}" '
           f'font-family="system-ui, -apple-system, Segoe UI, Roboto, sans-serif" font-size="12">',
           f'<rect width="100%" height="100%" fill="{SURFACE}"/>',
           f'<text x="{left}" y="20" font-size="14" font-weight="600" fill="{INK}">Hallucination rate by condition (95 % CI, site bootstrap)</text>']
    # legend: two keys, filled vs hollow dot (shape is the second encoding)
    lx = left
    for i, (_, label, color) in enumerate(SERIES):
        fill = color if i == 0 else SURFACE
        out.append(f'<circle cx="{lx + 5}" cy="36" r="5" fill="{fill}" stroke="{color}" stroke-width="2"/>')
        out.append(f'<text x="{lx + 15}" y="40" fill="{MUTED}">{label}</text>')
        lx += 30 + 7 * len(label)
    for t in range(0, 101, 20):                      # recessive grid
        out.append(f'<line x1="{x(t / 100)}" x2="{x(t / 100)}" y1="{top}" y2="{top + row_h * len(conds)}" stroke="{GRID}"/>')
        out.append(f'<text x="{x(t / 100)}" y="{top + row_h * len(conds) + 16}" text-anchor="middle" fill="{MUTED}">{t} %</text>')
    for r, c in enumerate(conds):
        y0 = top + row_h * r + row_h / 2
        out.append(f'<text x="{left - 10}" y="{y0 + 4}" text-anchor="end" fill="{INK}">{NAMES[c]}</text>')
        pooled = rep["conditions"][c]["pooled"]
        for i, (key, label, color) in enumerate(SERIES):
            ci = pooled[key]
            if ci[0] is None:
                continue
            y = y0 - 7 + 14 * i
            fill = color if i == 0 else SURFACE
            out.append(f'<g><title>{NAMES[c]}, {label.lower()}: {pct(ci)}</title>'
                       f'<line x1="{x(ci[1])}" x2="{x(ci[2])}" y1="{y}" y2="{y}" stroke="{color}" stroke-width="2" stroke-linecap="round"/>'
                       f'<circle cx="{x(ci[0])}" cy="{y}" r="5" fill="{fill}" stroke="{color}" stroke-width="2"/>'
                       f'<rect x="{x(ci[1]) - 4}" y="{y - 8}" width="{x(ci[2]) - x(ci[1]) + 8}" height="16" fill="transparent"/></g>')
    # effect panel: its own axis, -100..+100 points, zero line emphasised
    cmp = rep["comparisons"].get("primary")
    y_top = rates_h + 20
    out.append(f'<text x="{left}" y="{y_top}" font-size="14" font-weight="600" fill="{INK}">'
               f'Primary effect: gated − ungated, post-gate (percentage points)</text>')
    ex = lambda v: left + plot_w * (v + 1) / 2
    y = y_top + 50
    for t in range(-100, 101, 50):
        out.append(f'<line x1="{ex(t / 100)}" x2="{ex(t / 100)}" y1="{y - 10}" y2="{y + 14}" stroke="{INK if t == 0 else GRID}"/>')
        out.append(f'<text x="{ex(t / 100)}" y="{y + 30}" text-anchor="middle" fill="{MUTED}">{t:+d}</text>')
    out.append(f'<text x="{ex(-0.5)}" y="{y + 50}" text-anchor="middle" fill="{MUTED}">← gated better</text>')
    out.append(f'<text x="{ex(0.5)}" y="{y + 50}" text-anchor="middle" fill="{MUTED}">ungated better →</text>')
    if cmp and cmp["pooled_rate_diff"][0] is not None:
        d, lo, hi = cmp["pooled_rate_diff"]
        out.append(f'<g><title>Gated − ungated, post-gate: {100 * d:+.1f} points [{100 * lo:+.1f}, {100 * hi:+.1f}]</title>'
                   f'<line x1="{ex(lo)}" x2="{ex(hi)}" y1="{y}" y2="{y}" stroke="{INK}" stroke-width="2" stroke-linecap="round"/>'
                   f'<circle cx="{ex(d)}" cy="{y}" r="5" fill="{INK}" stroke="{SURFACE}" stroke-width="2"/></g>')
        out.append(f'<text x="{ex(d)}" y="{y - 16}" text-anchor="middle" fill="{INK}">{100 * d:+.1f} [{100 * lo:+.1f}, {100 * hi:+.1f}]</text>')
    else:
        out.append(f'<text x="{ex(0)}" y="{y - 12}" text-anchor="middle" fill="{MUTED}">not available (needs gated and ungated runs)</text>')
    out.append("</svg>")
    return "\n".join(out)


def write_all(claims_path: Path, runs_path: Path, out: Path, reps: int = metrics.BOOT_REPS) -> dict:
    labels, key = metrics.load_phase3()
    rep = metrics.report(metrics.load_claims(claims_path), metrics.read_jsonl(runs_path), labels, key, reps)
    out.mkdir(parents=True, exist_ok=True)
    (out / "results.md").write_text(tables(rep), encoding="utf-8")
    (out / "table_main.tex").write_text(latex_main(rep), encoding="utf-8")
    (out / "figure_rates.svg").write_text(figure(rep), encoding="utf-8")
    (out / "report.json").write_text(json.dumps(rep, indent=1, default=list), encoding="utf-8")
    return rep


def main(argv: list[str] | None = None) -> None:
    ap = argparse.ArgumentParser(description="Paper tables and figure from adjudicated claims")
    ap.add_argument("claims", type=Path)
    ap.add_argument("runs", type=Path)
    ap.add_argument("--out", type=Path, default=ROOT / "docs" / "results")
    ap.add_argument("--reps", type=int, default=metrics.BOOT_REPS)
    args = ap.parse_args(argv)
    write_all(args.claims, args.runs, args.out, args.reps)
    print(f"wrote {args.out}/results.md, table_main.tex, figure_rates.svg, report.json")


if __name__ == "__main__":
    main()
